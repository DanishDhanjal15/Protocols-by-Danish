// Scans src/lessons and writes src/lessons/index.ts: lazy loaders for every lesson,
// its Hinglish text (src/lessons/hinglish/<id>.json) and its try-it commands
// (src/lessons/tryit/<id>.json), plus the catalog.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "src", "lessons");
const ids = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && !f.startsWith("_") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();
const jsonIds = (sub) =>
  existsSync(path.join(dir, sub))
    ? readdirSync(path.join(dir, sub)).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).filter((id) => ids.includes(id)).sort()
    : [];
const hinglish = jsonIds("hinglish");
const tryit = jsonIds("tryit");
const map = (list, sub) => list.map((id) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(`./${sub}/${id}.json`)}),`).join("\n");

const out = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.
import type { Lesson } from "@/lib/lesson";
import type { LessonText, TryIt } from "@/lib/text";
import { LessonMeta, sortCatalog, toMeta } from "@/lib/catalog";

export const loaders: Record<string, () => Promise<{ default: Lesson }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify("./" + id)}),`).join("\n")}
};

const hinglishLoaders: Record<string, () => Promise<{ default: unknown }>> = {
${map(hinglish, "hinglish")}
};

const tryitLoaders: Record<string, () => Promise<{ default: unknown }>> = {
${map(tryit, "tryit")}
};

export const lessonIds = Object.keys(loaders);

export async function getLesson(id: string): Promise<Lesson | null> {
  const load = loaders[id];
  if (!load) return null;
  try {
    return (await load()).default;
  } catch (e) {
    console.error(\`Lesson \${id} failed to load\`, e);
    return null;
  }
}

export async function getHinglish(id: string): Promise<LessonText | null> {
  const load = hinglishLoaders[id];
  return load ? ((await load()).default as LessonText) : null;
}

export async function getTryIt(id: string): Promise<TryIt | null> {
  const load = tryitLoaders[id];
  return load ? ((await load()).default as TryIt) : null;
}

let cache: LessonMeta[] | null = null;
export async function getCatalog(): Promise<LessonMeta[]> {
  if (!cache) {
    const all = await Promise.all(lessonIds.map(getLesson));
    cache = sortCatalog(all.filter((l): l is Lesson => !!l).map(toMeta));
  }
  return cache;
}
`;
writeFileSync(path.join(dir, "index.ts"), out);
console.log(`registry: ${ids.length} lessons, ${hinglish.length} hinglish, ${tryit.length} try-it`);
