// Scans src/lessons/*.ts and writes src/lessons/index.ts (lazy loaders + catalog).
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
const dir = path.join(process.cwd(), "src", "lessons");
const ids = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && !f.startsWith("_") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();
const out = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.
import type { Lesson } from "@/lib/lesson";
import { LessonMeta, sortCatalog, toMeta } from "@/lib/catalog";

export const loaders: Record<string, () => Promise<{ default: Lesson }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify("./" + id)}),`).join("\n")}
};

export const lessonIds = Object.keys(loaders);

export async function getLesson(id: string): Promise<Lesson | null> {
  const load = loaders[id];
  if (!load) return null;
  try {
    return (await load()).default;
  } catch (e) {
    console.error(\`Lesson \${id} failed to load\`, e);
    return null;
  }
}

let cache: LessonMeta[] | null = null;
export async function getCatalog(): Promise<LessonMeta[]> {
  if (!cache) {
    const all = await Promise.all(lessonIds.map(getLesson));
    cache = sortCatalog(all.filter((l): l is Lesson => !!l).map(toMeta));
  }
  return cache;
}
`;
writeFileSync(path.join(dir, "index.ts"), out);
console.log(`registry: ${ids.length} lessons`);
